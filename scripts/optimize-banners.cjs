const fs = require("node:fs/promises");
const path = require("node:path");
const sharp = require("sharp");

const assetRoot = path.resolve(__dirname, "../src/assets");
const assets = [
  ["welcomeBanner", "brand/banners/pagabandida-welcome-v1.png"],
  ["canalBanner", "brand/banners/pagabandida-support-v2.png"],
  ["rankingBanner", "brand/banners/pagabandida-ranking-v2.png"],
  ["couponBanner", "brand/banners/pagabandida-wallet-v1.png"],
  ["historyArt", "brand/banners/pagabandida-history-v1.png"],
  ["analysisArt", "brand/banners/pagabandida-analysis-v1.png"],
];

async function main() {
  const imports = [];
  const exports = [];
  const report = [];
  for (const [name, source] of assets) {
    const input = path.join(assetRoot, source);
    const { width, height } = await sharp(input).metadata();
    const originalBytes = (await fs.stat(input)).size;
    const sizes = !name.endsWith("Art") ? [480, 768, 1200, 1600] : [240, 480, 768];
    const variants = [];
    for (const targetWidth of sizes.filter(size => size <= width)) {
      const output = `${path.dirname(source)}/optimized/${path.parse(source).name}-${targetWidth}.webp`;
      await fs.mkdir(path.dirname(path.join(assetRoot, output)), { recursive: true });
      // Resize proportionally: no crop, no upscaling, all embedded copy stays intact.
      const info = await sharp(input).resize({ width: targetWidth, withoutEnlargement: true })
        .webp({ quality: 84, effort: 6 }).toFile(path.join(assetRoot, output));
      const identifier = `${name}${targetWidth}`;
      imports.push(`import ${identifier} from "./${output}";`);
      variants.push({ identifier, width: info.width });
      report.push({ asset: name, width: info.width, height: info.height, kb: +(info.size / 1024).toFixed(1), saved: `${(100 * (1 - info.size / originalBytes)).toFixed(1)}%` });
    }
    const fallback = variants.find(variant => variant.width === 768);
    exports.push(`export const ${name} = {\n  src: ${fallback.identifier},\n  srcSet: \`${variants.map(variant => `\${${variant.identifier}} ${variant.width}w`).join(", ")}\`,\n  width: ${width},\n  height: ${height},\n};`);
  }
  await fs.writeFile(path.join(assetRoot, "responsiveImages.js"), [
    "// Generated by npm run optimize:banners. Keep the brand source artwork as masters.",
    ...imports, "", ...exports, "",
    "export const legacyCanalBanner = canalBanner;",
    "export const legacyRankingBanner = rankingBanner;",
    "export const whatsappBanner = canalBanner;", "",
  ].join("\n"));
  console.table(report);
}

main().catch(error => { console.error(error); process.exitCode = 1; });

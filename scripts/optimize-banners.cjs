const fs = require("node:fs/promises");
const path = require("node:path");
const sharp = require("sharp");

const assetRoot = path.resolve(__dirname, "../src/assets");
const assets = [
  ["welcomeBanner", "brand/banners/pagabandida-welcome-v1.png"],
  ["canalBanner", "brand/banners/pagabandida-support-v2.png"],
  ["rankingBanner", "brand/banners/pagabandida-ranking-v2.png"],
  ["couponBanner", "brand/banners/pagabandida-wallet-v1.png"],
  ["historyArt", "brand/banners/pagabandida-history-v1.png"],
  ["analysisArt", "brand/banners/pagabandida-analysis-v1.png"],
];

async function main() {
  const imports = [];
  const exports = [];
  const report = [];
  for (const [name, source] of assets) {
    const input = path.join(assetRoot, source);
    const { width, height } = await sharp(input).metadata();
    const sizes = name.endsWith("Art") ? [160, 240, 320, 480, 640, 768] : [320, 480, 640, 768, 960, 1200, 1600];
    const variants = { webp: [], avif: [] };
    for (const targetWidth of sizes.filter(size => size <= width)) {
      // Derivatives only: proportional resize, no crop or change to the source artwork.
      for (const format of ["webp", "avif"]) {
        const output = `${path.dirname(source)}/optimized/${path.parse(source).name}-${targetWidth}.${format}`;
        await fs.mkdir(path.dirname(path.join(assetRoot, output)), { recursive: true });
        const pipeline = sharp(input).resize({ width: targetWidth, withoutEnlargement: true });
        const encoded = format === "avif"
          ? pipeline.avif({ quality: 50, effort: 5, chromaSubsampling: "4:4:4" })
          : pipeline.webp({ quality: 76, effort: 6, smartSubsample: true });
        const info = await encoded.toFile(path.join(assetRoot, output));
        const identifier = `${name}${targetWidth}${format === "avif" ? "Avif" : ""}`;
        imports.push(`import ${identifier} from "./${output}";`);
        variants[format].push({ identifier, width: info.width });
        report.push({ asset: name, format, width: info.width, height: info.height, bytes: info.size, kb: +(info.size / 1024).toFixed(1) });
      }
    }
    const srcSet = items => `\`${items.map(item => `\${${item.identifier}} ${item.width}w`).join(", ")}\``;
    const mobileLimit = name.endsWith("Art") ? 640 : 960;
    const mobile = items => items.filter(item => item.width <= mobileLimit);
    const fallback = variants.webp.find(variant => variant.width === 768);
    exports.push(`export const ${name} = {\n  src: ${fallback.identifier},\n  srcSet: ${srcSet(variants.webp)},\n  sources: [\n    { type: "image/avif", media: "(max-width: 600px)", srcSet: ${srcSet(mobile(variants.avif))} },\n    { type: "image/avif", srcSet: ${srcSet(variants.avif)} },\n    { type: "image/webp", media: "(max-width: 600px)", srcSet: ${srcSet(mobile(variants.webp))} },\n  ],\n  width: ${width},\n  height: ${height},\n};`);
  }
  await fs.writeFile(path.join(assetRoot, "responsiveImages.js"), [
    "// Generated by npm run optimize:banners. Keep the brand source artwork as masters.",
    ...imports, "", ...exports, "",
    "export const legacyCanalBanner = canalBanner;",
    "export const legacyRankingBanner = rankingBanner;",
    "export const whatsappBanner = canalBanner;", "",
  ].join("\n"));
  console.table(report.map(({ bytes, ...entry }) => entry));
  const artifactDirectory = path.resolve(__dirname, "../artifacts/banner-optimization");
  await fs.mkdir(artifactDirectory, { recursive: true });
  await fs.writeFile(path.join(artifactDirectory, "after.json"), JSON.stringify(report, null, 2));
}

main().catch(error => { console.error(error); process.exitCode = 1; });
